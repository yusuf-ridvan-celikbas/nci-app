"""Generates iOS Localizable.strings/.stringsdict (en, tr) from the Android strings.xml.

Run from the repo root:  python ios/tools/gen_strings.py
Android stays the single source of truth; iOS-only strings live in IOS_EXTRA below.
"""
import os
import re
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
RES = os.path.join(ROOT, "app", "src", "main", "res")
OUT = os.path.join(ROOT, "ios", "App", "Resources")

IOS_EXTRA = {
    "en": {
        "age_declined": "Sorry, this app is only for adults of legal drinking age.",
        "name_change_note_ios": "Changes the name inside the app, widget and reminders. The home screen label stays the same.",
        "language_ios_note": "iOS sets the app language in the Settings app.",
        "widget_locked": "Unlock to see your session",
        "export_create": "Create export file",
    },
    "tr": {
        "age_declined": "Üzgünüz, bu uygulama yalnızca yasal içki içme yaşındaki yetişkinler içindir.",
        "name_change_note_ios": "Uygulama, widget ve hatırlatıcılardaki adı değiştirir. Ana ekrandaki ad aynı kalır.",
        "language_ios_note": "iOS'ta uygulama dili Ayarlar uygulamasından seçilir.",
        "widget_locked": "Oturumu görmek için kilidi açın",
        "export_create": "Dışa aktarma dosyası oluştur",
    },
}


def convert(text, formatted=True):
    text = text.replace("\\'", "'").replace('\\"', '"').replace("\\n", "\n")
    if formatted:
        text = re.sub(r"%(\d+\$)?s", lambda m: "%" + (m.group(1) or "") + "@", text)
        text = re.sub(r"%(\d+\$)?d", lambda m: "%" + (m.group(1) or "") + "ld", text)
    else:
        text = text.replace("%", "%%")
    return text


def escape(text):
    return text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def xml_escape(text):
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def load(path):
    tree = ET.parse(path)
    strings, plurals = {}, {}
    for el in tree.getroot():
        name = el.get("name")
        if el.tag == "string":
            strings[name] = convert("".join(el.itertext()), el.get("formatted") != "false")
        elif el.tag == "plurals":
            plurals[name] = {item.get("quantity"): convert("".join(item.itertext())) for item in el}
    return strings, plurals


def write(lang, strings, plurals):
    folder = os.path.join(OUT, f"{lang}.lproj")
    os.makedirs(folder, exist_ok=True)
    with open(os.path.join(folder, "Localizable.strings"), "w", encoding="utf-8", newline="\n") as f:
        f.write("/* Generated by ios/tools/gen_strings.py from Android strings.xml. Do not edit. */\n")
        for key in sorted(strings):
            f.write(f'"{key}" = "{escape(strings[key])}";\n')
    with open(os.path.join(folder, "Localizable.stringsdict"), "w", encoding="utf-8", newline="\n") as f:
        f.write('<?xml version="1.0" encoding="UTF-8"?>\n<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" '
                '"http://www.apple.com/DTDs/PropertyList-1.0.dtd">\n<plist version="1.0">\n<dict>\n')
        for key in sorted(plurals):
            forms = plurals[key]
            f.write(f"  <key>{key}</key>\n  <dict>\n    <key>NSStringLocalizedFormatKey</key>\n"
                    "    <string>%#@n@</string>\n    <key>n</key>\n    <dict>\n"
                    "      <key>NSStringFormatSpecTypeKey</key>\n      <string>NSStringPluralRuleType</string>\n"
                    "      <key>NSStringFormatValueTypeKey</key>\n      <string>ld</string>\n")
            for quantity in ("zero", "one", "two", "few", "many", "other"):
                if quantity in forms:
                    value = forms[quantity].replace("%1$ld", "%ld")
                    f.write(f"      <key>{quantity}</key>\n      <string>{xml_escape(value)}</string>\n")
            f.write("    </dict>\n  </dict>\n")
        f.write("</dict>\n</plist>\n")


def main():
    en, en_plurals = load(os.path.join(RES, "values", "strings.xml"))
    tr, tr_plurals = load(os.path.join(RES, "values-tr", "strings.xml"))
    en.update(IOS_EXTRA["en"])
    tr = {**en, **tr, **IOS_EXTRA["tr"]}
    tr_plurals = {**en_plurals, **tr_plurals}
    write("en", en, en_plurals)
    write("tr", tr, tr_plurals)
    missing = sorted(set(en) - set(load(os.path.join(RES, "values-tr", "strings.xml"))[0]) - set(IOS_EXTRA["tr"]))
    print(f"en: {len(en)} strings, {len(en_plurals)} plurals; tr fallback to en for: {missing}")


if __name__ == "__main__":
    main()
